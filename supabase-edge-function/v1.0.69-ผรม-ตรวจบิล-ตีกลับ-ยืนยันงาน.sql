--  ---------------------------------------------------------------
--  ลำดับการทำงานเต็ม ๆ หลังรอบนี้
--  ---------------------------------------------------------------
--    1. ปิดงาน (กรอกอะไหล่ + จำนวน + ประเภทเก็บเงิน)
--    2. ผู้รับเหมาเห็นฟอร์มแนบรูปทันที -> ส่งรูปกลับ
--    3. ผู้ตรวจสอบ + TUCK CR ตรวจรูป
--    4. แอดมินดึงงานเข้ารอบบิล -> แก้ไขราคา/อะไหล่ -> กดส่งบิลให้ผู้รับเหมา
--    5. ผู้รับเหมาเปิดตารางวางบิล ตรวจทีละแถวอะไหล่
--         - ถูกต้อง   -> กดยืนยันแถวนั้น
--         - ไม่ถูกต้อง -> กดตีกลับ พร้อมเขียนคอมเมนต์ว่าผิดตรงไหน
--    6. แอดมินเห็นแถวที่ถูกตีกลับพร้อมคอมเมนต์ -> แก้ -> กดส่งกลับให้ผู้รับเหมา
--       (วนข้อ 5-6 ได้ไม่จำกัดรอบ)
--    7. พอทุกแถวของเลขงานนั้นในรอบบิลถูกยืนยันครบ = ตัดบิลอัตโนมัติ งานจบ
--
--  จุดสำคัญ: "ผู้รับเหมายืนยันครบ" กลายเป็นตัวตัดบิล แทนขั้น TUCK CR แบบเดิม
--  เหตุผลอยู่ในหัวข้อ 3 ด้านล่าง
--
--  ---------------------------------------------------------------
--  ไฟล์นี้เพิ่มอะไรบ้าง
--  ---------------------------------------------------------------
--    1. คอลัมน์สถานะการตรวจของผู้รับเหมา ในตาราง billing_documents
--    2. ตาราง billing_row_comments  เก็บบทสนทนาตีกลับ-ตอบกลับ ทุกรอบ ไม่ทับกัน
--    3. ดัชนีสำหรับนับ "แถวที่รอตรวจ / ถูกตีกลับ" ขึ้นป้ายแจ้งเตือน
-- ============================================================================


-- ---------------------------------------------------------------------------
--  1. สถานะการตรวจบิลของผู้รับเหมา (รายแถวอะไหล่)
-- ---------------------------------------------------------------------------
--  ตรวจ "รายแถวอะไหล่" ไม่ใช่รายเลขงาน เพราะบิลใบหนึ่งผิดแค่อะไหล่ชิ้นเดียวก็มี
--  ถ้าตีกลับทั้งเลขงาน ผู้รับเหมาต้องมานั่งตรวจชิ้นที่ถูกอยู่แล้วใหม่หมดทุกรอบ
--
--  contractor_review_status รับ 4 ค่า
--    null       = ยังไม่เข้ากระบวนการตรวจ (ยังไม่ได้ส่งบิล หรือเป็นแถวเก่าก่อน v1.0.69)
--    'pending'  = ส่งบิลให้ผู้รับเหมาแล้ว รอผู้รับเหมาตรวจ
--    'approved' = ผู้รับเหมายืนยันแถวนี้แล้ว
--    'rejected' = ผู้รับเหมาตีกลับ รอแอดมินแก้แล้วส่งกลับ

alter table billing_documents add column if not exists contractor_review_status text;
alter table billing_documents add column if not exists contractor_reviewed_at   timestamptz;
alter table billing_documents add column if not exists contractor_reviewed_by   text;

-- นับว่าแถวนี้ถูกส่งให้ผู้รับเหมาดูมาแล้วกี่รอบ (ส่งครั้งแรก = 1, แก้แล้วส่งกลับ = 2, 3, ...)
-- มีไว้ให้ทั้งสองฝ่ายรู้ว่ากำลังคุยกันอยู่รอบที่เท่าไหร่ และใช้จัดกลุ่มคอมเมนต์ตามรอบ
alter table billing_documents add column if not exists revision_no integer not null default 0;

comment on column billing_documents.contractor_review_status is
  'ผลตรวจบิลของผู้รับเหมา: null=ยังไม่เข้ากระบวนการ · pending=รอตรวจ · approved=ยืนยันแล้ว · rejected=ตีกลับ';
comment on column billing_documents.revision_no is
  'ส่งให้ผู้รับเหมาดูมาแล้วกี่รอบ (0=ยังไม่เคยส่ง)';

-- แถวเก่าที่ส่งบิลไปแล้วก่อนรอบนี้ ต้องคงเป็น null ไว้เหมือนเดิม ห้ามตั้งเป็น pending
-- ถ้าตั้งเป็น pending ผู้รับเหมาจะถูกเรียกให้กลับมาไล่ยืนยันบิลเก่าทั้งหมดที่เคยจบไปแล้ว
-- และงานเก่าที่รอตัดบิลด้วยขั้น TUCK CR อยู่จะค้าง เพราะโค้ดจะเปลี่ยนไปรอผู้รับเหมาแทน
-- (โค้ดฝั่งเซิร์ฟเวอร์อ่าน null = "ใช้กติกาเดิม" ดูหัวข้อ 3)


-- ---------------------------------------------------------------------------
--  2. บทสนทนาตีกลับ-ตอบกลับ ของแต่ละแถวอะไหล่
-- ---------------------------------------------------------------------------
--  ทำไมต้องแยกตาราง ไม่เก็บเป็นคอลัมน์เดียวใน billing_documents:
--  รอบนี้ออกแบบให้ตีกลับ-แก้-ส่งกลับ วนได้ไม่จำกัดรอบ ถ้าเก็บคอลัมน์เดียว
--  คอมเมนต์รอบใหม่จะทับรอบเก่าทุกครั้ง พอเถียงกันว่า "บอกไปแล้วรอบที่แล้ว"
--  จะไม่เหลือหลักฐานเลยสักบรรทัด
--
--  billing_id เก็บเป็น text โดยตั้งใจ ไม่ใช่ bigint และไม่ผูก foreign key
--  เพราะตาราง billing_documents ถูกสร้างไว้ก่อนจะมีไฟล์ migration ชุดนี้
--  ชนิดของคอลัมน์ id จึงยืนยันจากไฟล์ในโปรเจกต์ไม่ได้ (อาจเป็น bigint หรือ uuid)
--  ถ้าเดาผิดแล้วประกาศเป็น bigint ไฟล์นี้จะรันไม่ผ่านตั้งแต่บรรทัดแรก
--  text รับได้ทั้งสองแบบ และฝั่งแอปส่งค่านี้มาเป็นข้อความอยู่แล้ว

create table if not exists billing_row_comments (
  id          bigint generated always as identity primary key,
  billing_id  text not null,                 -- id ของแถวใน billing_documents (เก็บเป็นข้อความ ดูเหตุผลข้างบน)
  customer_case text,                        -- เลขงาน เก็บซ้ำไว้ให้ค้นรวมทั้งเลขงานได้เร็ว
  revision_no integer,                       -- คุยกันอยู่รอบที่เท่าไหร่
  author_role text,                          -- 'contractor' | 'admin'
  author_name text,                          -- ชื่อคนที่กด เก็บไว้ตรวจย้อนหลัง
  action      text,                          -- 'rejected' | 'approved' | 'resent'
  message     text,                          -- ข้อความที่พิมพ์ (ตีกลับบังคับต้องมี)
  -- ใช้ now() ตรง ๆ ไม่ใช่ (now() at time zone 'utc')
  -- คอลัมน์เป็น timestamptz อยู่แล้ว ถ้าตัดโซนเวลาทิ้งก่อนแล้วค่อยยัดเข้า timestamptz
  -- Postgres จะตีความค่านั้นใหม่เป็นเวลาท้องถิ่นของเซิร์ฟเวอร์ = เวลาเพี้ยนไปหนึ่งช่วง
  created_at  timestamptz not null default now()
);

comment on table billing_row_comments is
  'ประวัติการตีกลับ/ยืนยัน/ส่งกลับ ของแต่ละแถวอะไหล่ในตารางวางบิล เก็บทุกรอบ ไม่ทับกัน';

-- อ่านบทสนทนาของแถวเดียว เรียงตามเวลา
create index if not exists billing_row_comments_billing_idx
  on billing_row_comments (billing_id, id);

-- ดูบทสนทนารวมทั้งเลขงาน
create index if not exists billing_row_comments_case_idx
  on billing_row_comments (customer_case);


-- ---------------------------------------------------------------------------
--  3. ดัชนีสำหรับป้ายแจ้งเตือน และการเช็ค "ยืนยันครบหรือยัง"
-- ---------------------------------------------------------------------------
--  ใช้ 2 งาน
--    ก. ผู้รับเหมาเปิดแอป -> นับว่ามีกี่แถวรอตัวเองตรวจ
--    ข. แอดมินเปิดแอป -> นับว่ามีกี่แถวถูกตีกลับกลับมา
create index if not exists billing_documents_contractor_review_idx
  on billing_documents (contractor, contractor_review_status);

--  ทุกครั้งที่ผู้รับเหมากดยืนยัน 1 แถว ระบบต้องเช็คว่าเลขงานนั้นในรอบบิลนั้น
--  ยืนยันครบทุกแถวหรือยัง ถ้าครบแล้วจะตัดบิลให้อัตโนมัติ
create index if not exists billing_documents_case_round_idx
  on billing_documents (customer_case, round_no);


-- ---------------------------------------------------------------------------
--  หมายเหตุสำคัญ — ทำไมตัวตัดบิลถึงย้ายมาอยู่ที่ผู้รับเหมา
-- ---------------------------------------------------------------------------
--  เดิม ขั้น "สิ้นสุดงาน" ของ TUCK CR ในการตรวจรูป เป็นตัวไปตั้ง completed_at
--  ในตารางวางบิล ซึ่งใช้ได้ตอนที่ลำดับงานเป็น "ส่งบิลก่อน แล้วค่อยส่งรูป"
--
--  พอ v1.0.68 สลับให้รูปมาก่อนบิล ตอน TUCK CR กดสิ้นสุด บิลยังไม่ถูกสร้างด้วยซ้ำ
--  จึงไม่มีแถวไหนให้ตัดเลย แล้วบิลที่สร้างทีหลังก็ไม่มีอะไรมาปิดให้ = ค้างถาวร
--  (ขึ้นข้อความว่า "ไม่มีแถวที่ต้องตัดบิล" ซึ่งดูเหมือนปกติ เลยไม่มีใครเอะใจ)
--
--  รอบนี้ย้ายตัวตัดบิลมาไว้ที่ "ผู้รับเหมายืนยันครบทุกแถว" ซึ่งเป็นขั้นสุดท้ายจริง ๆ
--  ของลำดับงานใหม่ ส่วนขั้น TUCK CR ยังตัดบิลให้เหมือนเดิม เฉพาะแถวที่
--  contractor_review_status เป็น null (= งานเก่าที่เดินตามลำดับเดิมค้างอยู่)
--  งานเก่าที่กำลังวิ่งอยู่จึงไม่สะดุด


-- ---------------------------------------------------------------------------
--  ตรวจผล
-- ---------------------------------------------------------------------------
select
  (select count(*) from information_schema.columns
    where table_schema = 'public' and table_name = 'billing_documents'
      and column_name in ('contractor_review_status','contractor_reviewed_at','contractor_reviewed_by','revision_no'))
    as "คอลัมน์ที่เพิ่มใน billing_documents (ต้องได้ 4)",
  (select count(*) from information_schema.tables
    where table_schema = 'public' and table_name = 'billing_row_comments')
    as "ตาราง billing_row_comments (ต้องได้ 1)",
  (select count(*) from billing_documents where contractor_review_status is not null)
    as "แถวที่อยู่ในกระบวนการตรวจแล้ว (รันครั้งแรกต้องได้ 0)",
  (select count(*) from billing_documents where sent_to_contractor = true and completed_at is null)
    as "แถวเก่าที่ส่งบิลแล้วยังไม่ตัดบิล (ยังใช้กติกาเดิม ไม่กระทบ)";
