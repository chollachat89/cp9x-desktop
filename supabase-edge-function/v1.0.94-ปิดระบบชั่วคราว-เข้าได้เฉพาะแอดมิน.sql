-- ============ บล็อก A — เปิดด่าน (รัน "ก่อน" deploy เซิร์ฟเวอร์) ============
-- ตั้งค่าไว้ล่วงหน้า พอ deploy เซิร์ฟเวอร์เสร็จ ด่านจะมีผลทันทีโดยไม่มีช่องว่างเวลา
-- อยากใส่ข้อความแจ้งเอง ให้เปลี่ยนเป็น  'on|ข้อความของคุณ'  (ขึ้นบนหน้าล็อกอินของคนที่ถูกกั้น)
insert into app_secrets (key, value)
values ('login_lock', 'on|ระบบปิดปรับปรุงชั่วคราวเพื่ออัปเดตเวอร์ชันใหม่ กรุณารอประกาศจากแอดมิน แล้วอัปเดตแอปก่อนเข้าใช้งาน')
on conflict (key) do update set value = excluded.value;

-- ดูว่าตั้งค่าติดแล้วจริง
select key, value from app_secrets where key = 'login_lock';


-- ============ บล็อก B — เด้งทุกคนออกจากระบบ (รัน "หลัง" deploy เซิร์ฟเวอร์) ============
--
-- ก่อนเด้ง ดูก่อนว่าตอนนี้ใครค้างอยู่ในระบบบ้าง (รันดูเฉย ๆ ไม่เปลี่ยนอะไร)
select
  username,
  display_name,
  role,
  case when session_token is null then 'ออกแล้ว' else 'ยังค้างอยู่' end as สถานะ,
  session_created_at
from contractors
order by (session_token is null), role, username;

-- เด้งออกทุกคน รวมแอดมินด้วย (ตามที่สั่ง: บังคับล็อกเอาต์ทุก user)
-- แอดมินล็อกอินกลับเข้ามาได้ทันทีด้วยรหัสผ่านเดิม · คนที่ไม่ใช่แอดมินจะถูกด่านกั้นไว้
update contractors set session_token = null where session_token is not null;

-- ยืนยันว่าไม่มีใครค้างอยู่แล้ว (ต้องได้ 0)
select count(*) as คนที่ยังค้างอยู่ from contractors where session_token is not null;


