--  v1.0.74 — เก็บกวาดบิลค้าง ของงานที่ไม่ต้องส่งให้ผู้รับเหมา
-- ============================================================================
--
--  รันในโปรเจกต์ที่จะใช้งาน (ทดสอบก่อน แล้วค่อยของจริง)
--  รันซ้ำได้ ไม่พัง — รอบที่สองจะไม่มีอะไรให้แก้แล้ว
--
--  ไฟล์นี้ไม่ได้เพิ่มคอลัมน์หรือตารางอะไรเลย แก้เฉพาะ "ข้อมูลที่ค้างอยู่" เท่านั้น
--
--  ---------------------------------------------------------------
--  ปัญหาที่ไฟล์นี้แก้
--  ---------------------------------------------------------------
--  ประเภทเก็บเงิน 2 แบบนี้ ไม่เก็บเงินฝั่งผู้รับเหมา
--      claim      = เคลมประกัน 3 เดือน  (ไม่เก็บทั้ง 2 ฝั่ง)
--      quotation  = ใบเสนอราคา          (เก็บเฉพาะฝั่ง CJ)
--  ทั้งระบบกรองแถวพวกนี้ออกจากฝั่งผู้รับเหมาหมด — ตาราง ค้นหา ยอดรวม เอกสาร
--  เขาจึงไม่มีวันเห็นแถวพวกนี้ และกดยืนยันให้ไม่ได้
--
--  แต่ตั้งแต่ v1.0.69 ตอนแอดมินกด "ส่งบิลให้ผู้รับเหมา" ระบบตั้งทุกแถวเป็น
--  contractor_review_status = 'pending' (รอผู้รับเหมาตรวจ) โดยไม่ดูประเภทเก็บเงิน
--  ผลคือแถวพวกนี้กลายเป็นคิวที่ไม่มีใครกดได้
--      - เลขงานที่เป็นประเภทนี้ล้วน ๆ ไม่มีวันเสร็จสิ้น ค้างสถานะ "ส่งงานแล้ว" ตลอดกาล
--      - รอบบิลนั้นไม่มีวันขึ้นว่าตัดครบ เพราะยังเหลือแถวที่ยังไม่ตัด
--      - ป้ายแจ้งเตือนฝั่งผู้รับเหมาขึ้นเลขค้าง กดยังไงก็ไม่ลด (เพราะเปิดมาก็ไม่เห็นแถว)
--
--  ตั้งแต่ v1.0.74 ตอนส่งบิล ระบบจะตั้งแถวพวกนี้เป็น 'not_required' และปิดบิลให้เลย
--  ไฟล์นี้มีไว้เก็บกวาด "ของที่ค้างไว้ก่อนหน้านั้น" เท่านั้น
-- ============================================================================


-- ---------------------------------------------------------------------------
--  0. ดูก่อนว่ามีอะไรค้างอยู่บ้าง (ยังไม่แก้อะไร)
-- ---------------------------------------------------------------------------
select
  (select count(*) from billing_documents
    where sent_to_contractor = true and completed_at is null
      and coalesce(billing_type, 'normal') in ('claim', 'quotation'))
    as "แถวเคลมประกัน/ใบเสนอราคา ที่ส่งบิลแล้วยังไม่ตัดบิล",
  (select count(distinct customer_case) from billing_documents
    where sent_to_contractor = true and completed_at is null
      and coalesce(billing_type, 'normal') in ('claim', 'quotation'))
    as "คิดเป็นกี่เลขงาน";


-- ---------------------------------------------------------------------------
--  1. เปลี่ยนป้ายจาก "รอผู้รับเหมาตรวจ" เป็น "ไม่ต้องให้ผู้รับเหมาตรวจ"
-- ---------------------------------------------------------------------------
--  ต้องแก้ก่อนข้อ 2 เพราะป้าย 'pending' คือสิ่งที่ทำให้ป้ายแจ้งเตือนฝั่งผู้รับเหมา
--  ขึ้นเลขค้าง ต่อให้ตัดบิลไปแล้วก็ตาม
--
--  ⚠ แตะเฉพาะแถวที่ยังไม่ตัดบิล และเป็น 'pending' เท่านั้น
--  แถวที่เป็น null (ส่งก่อน v1.0.69) ต้องคงเป็น null ไว้เหมือนเดิม เพราะเดินตามเส้นทางเดิม
--  ส่วน 'approved' / 'rejected' แปลว่ามีคนกดไปแล้วจริง ห้ามลบประวัตินั้นทิ้ง

update billing_documents
set contractor_review_status = 'not_required'
where sent_to_contractor = true
  and completed_at is null
  and contractor_review_status = 'pending'
  and coalesce(billing_type, 'normal') in ('claim', 'quotation');


-- ---------------------------------------------------------------------------
--  2. ตัดบิลให้แถวที่ไม่เหลืออะไรให้รอแล้ว
-- ---------------------------------------------------------------------------
--  ปิดเฉพาะแถวที่ผ่านครบทั้ง 3 ข้อ — เข้มไว้ก่อน ปิดพลาดแก้คืนยากกว่าปิดช้า
--
--    ก. เป็นเคลมประกัน/ใบเสนอราคา และส่งบิลไปแล้ว (ไม่แตะแถวที่ยังกรอกไม่เสร็จ)
--    ข. ในรอบบิลเดียวกันของเลขงานนั้น ไม่เหลือแถวฝั่งผู้รับเหมาที่ยังไม่ตัดบิล
--       (ถ้ายังเหลือ แปลว่างานนี้ยังรอผู้รับเหมาอยู่จริง ๆ ปล่อยให้เดินตามทางปกติ
--        พอเขายืนยันครบ ระบบจะตัดบิลให้ทั้งกลุ่มรวมแถวพวกนี้ด้วยอยู่แล้ว)
--    ค. ฝั่งรูปผ่านแล้ว — ใช้กติกาเดียวกับในแอปเป๊ะ ๆ คือ
--       "มีฟอร์มที่ยืนยันรูปแล้วอย่างน้อย 1 ใบ" หรือ "ไม่เคยมีฟอร์มเลย"
--       ไม่เคยมีฟอร์ม = งานประเภทนี้ไม่เคยถูกออกฟอร์มให้ตั้งแต่แรก (ระบบยกเว้นให้อยู่แล้ว)
--       ถ้าเขียนเข้มกว่านี้ (เช่น "ห้ามมีใบที่ยังไม่ยืนยันเลย") จะกลายเป็นคนละกติกากับแอป
--       แล้วจะเหลือแถวที่ไฟล์นี้ไม่ยอมปิด และแอปก็ไม่มีจังหวะไหนไปปิดให้อีก = ค้างต่อ

update billing_documents b
set completed_at = now()
where b.sent_to_contractor = true
  and b.completed_at is null
  and coalesce(b.billing_type, 'normal') in ('claim', 'quotation')
  and not exists (
    select 1 from billing_documents x
    where x.customer_case = b.customer_case
      and x.round_no is not distinct from b.round_no
      and coalesce(x.billing_type, 'normal') not in ('claim', 'quotation')
      and x.completed_at is null
  )
  and (
    not exists (select 1 from job_form_submissions s where s.customer_case = b.customer_case)
    or exists (select 1 from job_form_submissions s
                where s.customer_case = b.customer_case and s.status = 'approved')
  );


-- ---------------------------------------------------------------------------
--  ตรวจผล
-- ---------------------------------------------------------------------------
--  แถวแรกควรเหลือ 0
--  ถ้ายังไม่เป็น 0 ไม่ได้แปลว่าพัง — แปลว่าเลขงานนั้นยังติดข้อ ข. หรือ ค. อยู่จริง
--  ให้ดูคอลัมน์ที่ 2 กับ 3 ว่าติดเพราะอะไร แล้วแก้ที่ต้นเหตุนั้น (ยืนยันรูป / รอผู้รับเหมา)
select
  (select count(*) from billing_documents
    where sent_to_contractor = true and completed_at is null
      and coalesce(billing_type, 'normal') in ('claim', 'quotation'))
    as "ยังค้างอยู่ (ควรเป็น 0)",
  (select count(*) from billing_documents b
    where b.sent_to_contractor = true and b.completed_at is null
      and coalesce(b.billing_type, 'normal') in ('claim', 'quotation')
      and exists (select 1 from job_form_submissions s where s.customer_case = b.customer_case)
      and not exists (select 1 from job_form_submissions s
                       where s.customer_case = b.customer_case and s.status = 'approved'))
    as "ในนั้น ติดเพราะยังไม่ยืนยันรูป",
  (select count(*) from billing_documents
    where contractor_review_status = 'not_required')
    as "แถวที่ติดป้าย ไม่ต้องส่ง ผรม. แล้ว";
