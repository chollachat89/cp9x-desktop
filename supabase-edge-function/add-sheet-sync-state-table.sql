-- ถ้ายังไม่เคยรันไฟล์นี้ ไม่ต้องรันก็ได้ ถ้าเคยรันไปแล้ว ทิ้งตาราง sheet_sync_state ไว้เฉย ๆ ได้ ไม่มีผลอะไร
