-- ============================================================================
-- ตารางติดตามสถานะซิงค์ไป Google Sheet แบบ "เติมเฉพาะแถวใหม่ + อัปเดตแถวเดิมที่เคยส่งแล้ว"
-- แทนแบบเดิมที่ "ลบข้อมูลทั้งหมดในชีตแล้วเขียนใหม่ทุกครั้ง" (เสี่ยงข้อมูลเก่ากว่า 5000 แถวหลุดหาย)
--
-- วิธีทำงาน: เก็บไว้ว่าแต่ละแถวข้อมูล (record_key) ของแต่ละแท็บ (sheet_name) ถูกเขียนอยู่ที่แถวไหนใน Sheet
-- (row_number) ครั้งถัดไปที่ซิงค์ ถ้าเจอ record_key เดิม = เขียนทับแถวเดิมตำแหน่งนั้น (ไม่เพิ่มซ้ำ)
-- ถ้าไม่เคยเจอ = เพิ่มต่อท้ายแถวใหม่ แล้วจำตำแหน่งไว้
--
-- วิธีใช้: เปิด Supabase Dashboard ของโปรเจกต์ CP9X -> SQL Editor -> New query
-- แล้ววางโค้ดด้านล่างนี้ทั้งหมด กด Run (รันได้ครั้งเดียวพอ)
--
-- สำคัญ: ก่อนใช้งานฟีเจอร์นี้ครั้งแรก แนะนำให้ไปลบข้อมูลแถวเก่าทั้งหมดในทุกแท็บของ Google Sheet ปลายทาง
-- ออกก่อน (เว้นแถวหัวตารางแถวที่ 1 ไว้) เพราะระบบซิงค์รอบแรกหลังอัปเดตจะมองว่าทุกแถวเป็น "ข้อมูลใหม่"
-- (ยังไม่เคยมีสถานะซิงค์บันทึกไว้) แล้วเพิ่มต่อท้ายข้อมูลเดิมที่ยังค้างอยู่ในชีต ทำให้ซ้ำกันได้ถ้าไม่ล้างก่อน
-- ============================================================================

create table if not exists sheet_sync_state (
    sheet_name text not null,
    record_key text not null,
    row_number bigint not null,
    updated_at timestamptz not null default now(),
    primary key (sheet_name, record_key)
);

-- ตรวจสอบผลลัพธ์
select table_name from information_schema.tables where table_name = 'sheet_sync_state';
