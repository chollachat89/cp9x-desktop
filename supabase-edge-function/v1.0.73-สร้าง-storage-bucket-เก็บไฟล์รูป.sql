--  ผู้รับเหมากดส่งรูป แล้วขึ้นข้อความ
--
--      อัปโหลดไฟล์ล้มเหลว: Bucket not found
--
--  แปลว่าโปรเจกต์นี้ยังไม่มี "ถังเก็บไฟล์" ชื่อ job-form-submissions
--  ซึ่งเป็นที่ที่ระบบเอาไฟล์ PDF/รูปของผู้รับเหมาไปวางไว้
--
--  ทำไมถึงขาด: ชุดสคริปต์ตั้งระบบทดสอบ (ขั้นที่ 2-5) คัดลอกเฉพาะ "ตารางกับฟังก์ชัน"
--  ในสคีมา public เท่านั้น ส่วน Storage อยู่คนละที่กันโดยสิ้นเชิง (สคีมา storage)
--  จึงไม่เคยถูกคัดลอกตามมาด้วย และไม่มีใครรู้จนกว่าจะมีคนลองกดส่งรูปจริง
--
--  โปรเจกต์ของจริงมีถังนี้อยู่แล้ว (เพราะสร้างด้วยมือตอนทำระบบครั้งแรก)
--  ไฟล์นี้จึงมีผลจริงกับโปรเจกต์ทดสอบเป็นหลัก แต่รันกับของจริงก็ไม่มีอะไรเสียหาย
--  เพราะ on conflict do nothing จะข้ามให้เองถ้ามีอยู่แล้ว
-- ============================================================================


-- ---------------------------------------------------------------------------
--  1. สร้างถังเก็บไฟล์
-- ---------------------------------------------------------------------------
--  public = true จำเป็น ไม่ใช่เลือกได้
--  โค้ดฝั่งเซิร์ฟเวอร์ใช้ getPublicUrl() แล้วเก็บลิงก์นั้นลงคอลัมน์ file_url
--  แอดมินเปิดไฟล์จากลิงก์นั้นตรง ๆ ถ้าตั้งเป็น private ลิงก์จะเปิดไม่ได้ทุกไฟล์
--
--  ⚠ หมายถึงใครมีลิงก์ก็เปิดไฟล์ได้ แต่ลิงก์เดาไม่ได้
--  (ชื่อไฟล์เป็น เวลา + สุ่ม 6 ตัวอักษร) และเป็นพฤติกรรมเดียวกับของจริงที่ใช้อยู่แล้ว

insert into storage.buckets (id, name, public)
values ('job-form-submissions', 'job-form-submissions', true)
on conflict (id) do nothing;

-- มีถังอยู่แล้วแต่เป็น private อยู่ ให้เปลี่ยนเป็น public
-- (เผื่อกรณีเคยสร้างด้วยมือแล้วลืมติ๊ก public ซึ่งจะอัปโหลดผ่านแต่เปิดไฟล์ไม่ได้
--  เป็นอาการที่หาสาเหตุยากกว่า Bucket not found มาก เพราะดูเหมือนสำเร็จทุกขั้น)
update storage.buckets set public = true
where id = 'job-form-submissions' and public is distinct from true;


-- ---------------------------------------------------------------------------
--  2. เรื่องสิทธิ์ (ไม่ต้องสร้าง policy เพิ่ม)
-- ---------------------------------------------------------------------------
--  การอัปโหลดทั้งหมดวิ่งผ่าน Edge Function ซึ่งใช้ service_role key
--  service_role ข้าม RLS อยู่แล้ว จึงเขียนไฟล์ได้โดยไม่ต้องมี policy
--
--  ส่วนการอ่าน ใช้ลิงก์สาธารณะของถัง public ซึ่งไม่ผ่าน RLS เช่นกัน
--
--  แปลว่า "ไม่ต้องสร้าง policy อะไรเลย" — ถ้าไปสร้าง policy เพิ่มโดยไม่จำเป็น
--  มีโอกาสเปิดช่องให้ anon key เขียนไฟล์เข้ามาได้ ซึ่งอันตรายกว่าเดิม


-- ---------------------------------------------------------------------------
--  ตรวจผล
-- ---------------------------------------------------------------------------
select
  (select count(*) from storage.buckets where id = 'job-form-submissions')
    as "ถัง job-form-submissions (ต้องได้ 1)",
  (select public from storage.buckets where id = 'job-form-submissions')
    as "เป็นสาธารณะหรือยัง (ต้องได้ true)",
  (select count(*) from storage.objects where bucket_id = 'job-form-submissions')
    as "จำนวนไฟล์ที่มีอยู่ตอนนี้";
