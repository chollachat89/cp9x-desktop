-- =====================================================================
--  E. ตรวจผลหลังแก้ — ต้องได้ 0 ทั้ง 2 บรรทัด
-- =====================================================================

select 'วันที่ยังผิดอยู่' as "หัวข้อ", count(*) as "เหลือกี่แถว"
from public.close_issues c
where btrim(coalesce(c.fix_date,'')) = ''
   or array_length(regexp_split_to_array(btrim(coalesce(c.fix_date,'')),'[-/]'),1) is distinct from 3
   or c.fix_date like '%2029%'
union all
select 'จองค้างแต่ไม่มีบิล', count(*)
from public.billing_job_registry r
where not exists (select 1 from public.billing_documents b
                  where b.customer_case = split_part(r.customer_case,'__asset__',1));


