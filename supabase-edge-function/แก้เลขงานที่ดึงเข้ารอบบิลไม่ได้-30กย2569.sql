--  D. สาเหตุที่ 2 — งานถูก "จองคิว" ค้างไว้ แต่ไม่มีบิลจริง
-- =====================================================================
--  ตอนกดยืนยันสร้างรอบบิล ระบบจองคิวเลขงานไว้ก่อน แล้วค่อยสร้างแถวบิล
--  ถ้าพังกลางทาง จะเหลือการจองค้างโดยไม่มีบิล -> งานนั้นถูกข้ามตลอดไป
--
--  ตรวจแล้วมี 5 คีย์จองค้าง แต่แยกเป็น 2 กลุ่ม:
--
--   กลุ่มที่ 1 — ไม่มีทั้งเปิดงานและปิดงานในระบบแล้ว (4 งาน)
--     CM20260805-0156 · CM20260828-0078 · CM20260830-0320 · CM20260903-9999
--     = งานถูกลบไปแล้ว หรือเป็นข้อมูลทดสอบ  ไม่มีอะไรให้วางบิลอยู่แล้ว
--     ลบการจองทิ้งก็ได้ ไม่ลบก็ไม่มีผลเสีย
--
--   กลุ่มที่ 2 — งานจริงที่เคยติด (1 งาน) — ✓ แก้แล้ว (ตรวจ 2 ต.ค. 2569)
--     CM20260905-0182 · ทีมพี่โอม · ตอนนี้อยู่ในรอบบิลที่ 77 แล้ว 1 แถว
--     (ถูกเพิ่มเข้ารอบด้วยกล่อง "เพิ่มเลขงานเข้ารอบบิล" ซึ่งไม่ผ่านการจองคิว)
--     ไม่ต้องทำอะไรกับงานนี้แล้ว

-- ดูก่อน (ยังไม่ลบ)
select r.customer_case as "คีย์จองที่จะลบ",
       split_part(r.customer_case,'__asset__',1) as "เลขงาน"
from public.billing_job_registry r
where not exists (select 1 from public.billing_documents b
                  where b.customer_case = split_part(r.customer_case,'__asset__',1))
order by 2;

