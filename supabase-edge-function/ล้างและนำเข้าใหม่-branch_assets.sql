-- ==========================================================
-- บล็อก A — ดูของเดิมก่อน  (อ่านอย่างเดียว ไม่ลบอะไร)
-- จดตัวเลขไว้ เอาไว้เทียบกับของใหม่หลังนำเข้าเสร็จ
-- ==========================================================

select
  count(*)                          as "จำนวนแถวทั้งหมด",
  count(distinct branch_code)       as "จำนวนสาขา",
  count(distinct asset_no)          as "จำนวนเลขทรัพย์สินไม่ซ้ำ",
  min(length(branch_code))          as "รหัสสาขาสั้นสุด (กี่ตัวอักษร)",
  max(length(branch_code))          as "รหัสสาขายาวสุด"
from branch_assets;


-- ==========================================================
-- บล็อก B — สำรองของเดิมไว้ก่อน  ⚠ ห้ามข้าม
--
-- ก๊อปทั้งตารางเก็บไว้เป็นตารางสำรอง ถ้าไฟล์ใหม่มีปัญหาจะได้เอากลับมาได้
-- ตารางสำรองไม่กระทบการทำงานของระบบ ปล่อยไว้ได้ ลบทีหลังเมื่อมั่นใจแล้ว
-- ==========================================================

drop table if exists backup_branch_assets_old;
create table backup_branch_assets_old as select * from branch_assets;

-- ต้องได้จำนวนเท่ากับบล็อก A เป๊ะ ถ้าไม่เท่าห้ามไปต่อ
select count(*) as "จำนวนแถวที่สำรองไว้" from backup_branch_assets_old;


-- ==========================================================
-- บล็อก C — ⚠⚠ ลบข้อมูลทั้งตาราง ⚠⚠
--
-- หลังรันบล็อกนี้ ตาราง branch_assets จะว่างเปล่าทันที
-- ผลที่เกิดกับแอประหว่างที่ยังไม่ได้นำเข้าไฟล์ใหม่:
--   - ช่องเลือกเลขทรัพย์สินในฟอร์มปิดงาน จะไม่มีรายการให้เลือก
--   - ฟอร์มแนบรูปวางบิล ช่อง "รายละเอียดทรัพย์สิน" จะว่าง
-- ข้อมูลงาน เปิดงาน ปิดงาน และบิล ไม่ได้รับผลกระทบ เพราะอยู่คนละตาราง
--
-- รันบล็อก B ให้ผ่านก่อนเสมอ ไม่งั้นย้อนกลับไม่ได้
-- ==========================================================

truncate table branch_assets restart identity;

-- ต้องได้ 0
select count(*) as "เหลือกี่แถว (ต้องเป็น 0)" from branch_assets;


-- ==========================================================
-- ▶ ถึงตรงนี้ ให้ไปนำเข้าไฟล์ใหม่ก่อน แล้วค่อยกลับมารันบล็อก D
--   วิธีนำเข้าอยู่ในไฟล์ "วิธีนำเข้าไฟล์ branch_assets.md"
-- ==========================================================


-- ==========================================================
-- บล็อก D — ตรวจไฟล์ใหม่หลังนำเข้าเสร็จ  (อ่านอย่างเดียว)
--
-- 3 ข้อนี้คือจุดที่พังบ่อยที่สุดเวลานำเข้าจาก Excel
-- และเป็นแบบที่ "ไม่มี error ขึ้นเลย" แต่แอปหาข้อมูลไม่เจอทีหลัง
-- ==========================================================

-- D1) ภาพรวม เทียบกับบล็อก A
select
  count(*)                    as "จำนวนแถวทั้งหมด",
  count(distinct branch_code) as "จำนวนสาขา",
  count(distinct asset_no)    as "จำนวนเลขทรัพย์สินไม่ซ้ำ"
from branch_assets;

-- D2) ⚠ รหัสสาขาต้องเป็น 4 หลักมี 0 นำหน้าเสมอ เช่น '0002' ไม่ใช่ '2'
--     เพราะโค้ดฝั่งเซิร์ฟเวอร์เติม 0 ให้ครบ 4 หลักแล้วค้นแบบตรงตัว
--     ถ้าในตารางเก็บเป็น '2' จะหาไม่เจอเลย ทั้งที่ข้อมูลมีอยู่ — ไม่มี error ให้เห็น
--     Excel ชอบตัด 0 นำหน้าทิ้งเวลาบันทึกเป็น CSV จึงเจอปัญหานี้บ่อยมาก
--
--     ต้องได้ 0 แถว
select branch_code as "รหัสสาขาที่ไม่ใช่ 4 หลัก (ต้องแก้)",
       count(*)    as "จำนวนแถวที่กระทบ"
from branch_assets
where branch_code is null or length(branch_code) <> 4
group by branch_code
order by branch_code;

--     ถ้าเจอ ให้เติม 0 ให้ครบ 4 หลักด้วยคำสั่งนี้ (ปลอดภัย รันซ้ำได้):
--       update branch_assets
--       set branch_code = lpad(regexp_replace(branch_code, '\D', '', 'g'), 4, '0')
--       where length(branch_code) <> 4;

-- D3) ⚠ เลขทรัพย์สินต้องเป็นตัวเลข 12 หลัก
--     ระบบบังคับ 12 หลักตอนปิดงานอยู่แล้ว ถ้าทะเบียนเก็บไม่ครบ 12 หลักจะจับคู่กันไม่ได้
--     ต้องได้ 0 แถว
select asset_no as "เลขทรัพย์สินที่ไม่ใช่ตัวเลข 12 หลัก",
       branch_code as "สาขา",
       count(*)  as "จำนวนแถว"
from branch_assets
where asset_no is null or asset_no !~ '^\d{12}$'
group by asset_no, branch_code
order by branch_code, asset_no
limit 100;

-- D4) เลขทรัพย์สินซ้ำข้ามสาขา — ไม่ใช่ข้อผิดพลาดเสมอไป แต่ควรดูไว้
--     ถ้าเลขเดียวกันอยู่ 2 สาขา ระบบจะหยิบคำอธิบายแถวแรกที่เจอมาใช้
select asset_no                        as "เลขทรัพย์สิน",
       count(distinct branch_code)     as "อยู่กี่สาขา",
       string_agg(distinct branch_code, ', ' order by branch_code) as "สาขาที่พบ"
from branch_assets
group by asset_no
having count(distinct branch_code) > 1
order by asset_no
limit 50;

-- D5) ดูตัวอย่างข้อมูลจริง 20 แถว ตาดูอีกทีว่าหน้าตาถูกต้อง
select id, branch_code, branch_name, asset_no, description
from branch_assets
order by branch_code, asset_no
limit 20;


