-- ==========================================================
-- ล้างตาราง branch_assets แล้วนำเข้าไฟล์ใหม่
--
-- ⚠⚠ ไฟล์นี้มีคำสั่งลบข้อมูลทั้งตาราง กู้คืนเองไม่ได้
--     ห้ามวางทั้งไฟล์แล้วกด Run รวดเดียว
--     ให้รันทีละบล็อก A → B → C แล้วค่อยนำเข้าไฟล์ จากนั้นรัน D ตรวจผล
--
-- ที่รัน: https://supabase.com/dashboard/project/hefnjozijflnhdunmewl/sql/new
