-- ขั้นที่ 1: ตรวจสอบก่อนว่ามีเลขงานซ้ำอยู่แล้วในระบบหรือไม่ (รันสองคำสั่งนี้ก่อนเสมอ)
-- ถ้าไม่มีแถวไหนถูกคืนกลับมาเลย (ผลลัพธ์ว่างเปล่าทั้งคู่) แปลว่าปลอดภัย ไปขั้นที่ 2 ได้เลย
-- ถ้ามีแถวถูกคืนมา แปลว่ามีเลขซ้ำอยู่แล้วในข้อมูลเก่า ต้องแก้ไข/ลบข้อมูลซ้ำให้เรียบร้อยก่อน
-- ไม่งั้นขั้นที่ 2 จะรันไม่ผ่าน (Postgres จะปฏิเสธเพราะสร้าง unique index บนข้อมูลที่ซ้ำอยู่แล้วไม่ได้)

select main_id, count(*) as จำนวนซ้ำ
from open_issues
group by main_id
having count(*) > 1;

select job_id, count(*) as จำนวนซ้ำ
from close_issues
group by job_id
having count(*) > 1;


-- ขั้นที่ 2: สร้างกฎห้ามซ้ำถาวรที่ระดับฐานข้อมูล (รันหลังจากขั้นที่ 1 ยืนยันว่าไม่มีข้อมูลซ้ำแล้วเท่านั้น)
-- IF NOT EXISTS แปลว่ารันซ้ำได้อย่างปลอดภัย ไม่พังถ้าเคยรันไปแล้ว

create unique index if not exists open_issues_main_id_uniq
    on open_issues (main_id);

create unique index if not exists close_issues_job_id_uniq
    on close_issues (job_id);


-- ตรวจสอบผลลัพธ์ (ควรเห็น 2 แถวนี้ในรายการ index ของตาราง)
select indexname, tablename
from pg_indexes
where indexname in ('open_issues_main_id_uniq', 'close_issues_job_id_uniq');
