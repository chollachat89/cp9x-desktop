-- ---------------------------------------------------------------------------
--  1. รายการอะไหล่แบบมีโครงสร้าง
-- ---------------------------------------------------------------------------
--  เดิมคอลัมน์ parts เก็บเป็นข้อความก้อนเดียว เช่น
--      1. P829-ตะแกรง FCU--ขนาด 10 นิ้ว = 10
--      2. NP001-อะไหล่นอกระบบ = 2
--
--  ข้อความล้วนเก็บ "ประเภทเก็บเงินของอะไหล่แต่ละชิ้น" ไม่ได้ จึงเพิ่มคอลัมน์ใหม่
--  โดย **ไม่ลบของเดิม** เพราะ parts ยังถูกใช้ส่งขึ้น Google Sheet และแสดงในรายงาน
--  แถวเก่าทั้งหมดจะมี parts_json เป็น null ซึ่งโค้ดรองรับไว้แล้ว (ถอยไปอ่าน parts แทน)
--
--  รูปแบบข้อมูลที่เก็บ — array ของ object เรียงตามลำดับที่กรอก
--    [
--      {"no":1,"text":"P829-ตะแกรง FCU--ขนาด 10 นิ้ว = 10",
--       "partCode":"P829","qty":10,"billingType":"normal"}
--    ]
--
--  billingType รับได้ 4 ค่าเท่านั้น ตรงกับ BILLING_TYPE_VALUES ใน index.ts
--    normal         เก็บเงินปกติ           <- ค่าเริ่มต้น
--    claim          เคลมประกัน 3 เดือน     ไม่เก็บทั้ง CJ และผู้รับเหมา
--    contractor_cr  เคลมอะไหล่             เก็บเฉพาะฝั่งผู้รับเหมา
--    quotation      ใบเสนอราคา             ไม่เก็บฝั่งผู้รับเหมา

alter table close_issues add column if not exists parts_json jsonb;

comment on column close_issues.parts_json is
  'รายการอะไหล่แบบมีโครงสร้าง พร้อมประเภทเก็บเงินรายชิ้น (ตั้งตอนปิดงาน) '
  'null = แถวเก่าที่ปิดงานก่อน v1.0.68 ให้ถอยไปอ่านคอลัมน์ parts แทน';

-- ดัชนีแบบ GIN ใช้ตอนค้นว่าเลขงานไหนมีอะไหล่ประเภทไหนบ้าง
-- (ใช้ตัดงานที่อะไหล่ทุกชิ้นเป็นเคลมประกัน ออกจากแท็บฟอร์มของผู้รับเหมา)
create index if not exists close_issues_parts_json_idx on close_issues using gin (parts_json);


-- ---------------------------------------------------------------------------
--  2. เส้นแบ่งเวลาของกฎ "ต้องยืนยันรูปก่อนวางบิล"
-- ---------------------------------------------------------------------------
--  ปัญหาที่ต้องกันไว้ก่อน:
--  ถ้าบังคับกฎใหม่กับข้อมูลเก่าทั้งหมด งานที่ปิดไปแล้วทุกใบจะวางบิลไม่ได้ทันที
--  เพราะไม่เคยมีฟอร์มรูปให้ยืนยันตั้งแต่แรก = งานค้างทั้งระบบตั้งแต่วินาทีที่ deploy
--  ซึ่งจะดูเหมือนระบบพัง ทั้งที่เป็นผลของกฎใหม่
--
--  จึงบันทึก "เวลาที่เริ่มใช้กฎ" ไว้ แล้วให้กฎมีผลเฉพาะงานที่ปิดตั้งแต่เวลานั้นเป็นต้นไป
--  งานที่ปิดก่อนหน้านี้ยังวางบิลได้ตามปกติเหมือนเดิม
--
--  on conflict do nothing = ถ้ารันไฟล์นี้ซ้ำ จะไม่เลื่อนเส้นแบ่งเวลาไปข้างหน้า
--  (ถ้าเลื่อน งานที่ปิดระหว่างนั้นจะหลุดกฎไปโดยไม่ตั้งใจ)

insert into app_secrets (key, value)
values ('photo_form_gate_start_at', now() at time zone 'utc')
on conflict (key) do nothing;

-- อยากเลื่อนเส้นแบ่งเอง (เช่น อยากให้กฎมีผลพรุ่งนี้เที่ยงคืน) ใช้คำสั่งนี้
--   update app_secrets set value = '2026-10-01T00:00:00Z' where key = 'photo_form_gate_start_at';
--
-- อยากปิดกฎชั่วคราว ให้วางบิลได้เหมือนเดิมทุกงาน ใช้คำสั่งนี้
--   update app_secrets set value = 'off' where key = 'photo_form_gate_start_at';


-- ---------------------------------------------------------------------------
--  3. ดัชนีสำหรับการเช็ค "ยืนยันรูปหรือยัง"
-- ---------------------------------------------------------------------------
--  ทุกครั้งที่แอดมินกดดูตัวอย่างรอบบิล ระบบต้องเช็คทีละเลขงานว่ามีฟอร์มที่ถูก
--  อนุมัติแล้วหรือยัง ถ้าไม่มีดัชนีจะต้องไล่อ่านทั้งตารางทุกครั้ง

create index if not exists job_form_submissions_case_status_idx
  on job_form_submissions (customer_case, status);


