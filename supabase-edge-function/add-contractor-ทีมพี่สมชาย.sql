-- ---------------------------------------------------------------- บล็อก A
-- เพิ่มผู้ใช้ (ข้ามอัตโนมัติถ้ามี username นี้อยู่แล้ว จึงรันซ้ำได้ไม่เกิดผู้ใช้ซ้ำ)
insert into contractors (username, password_hash, display_name, role)
select
  'contractor11',
  'a0c664768c7aadf3b6c8c19633694ee181aa5a125fafbc5d91d7695c502ff2a6',
  'ทีมพี่สมชาย',
  'contractor'
where not exists (
  select 1 from contractors where username = 'contractor11'
);

-- ตรวจผลทันที ควรเห็น 1 แถว และ role ต้องเป็น contractor
select id, username, display_name, role
from contractors
where username = 'contractor11';


-- ---------------------------------------------------------------- บล็อก B
-- เช็คว่าชื่อ "ทีมพี่สมชาย" สะกดตรงกับชื่อผู้รับเหมาที่ใช้ในตารางวางบิลจริงหรือไม่
-- ถ้าคอลัมน์ "มีงานในตารางวางบิล" เป็น 0 ทั้งที่ควรมีงานอยู่แล้ว แปลว่าสะกดไม่ตรงกัน
-- ให้ดูรายชื่อจากบล็อก C แล้วแก้ display_name ให้ตรง (ดูคำสั่งแก้ในบล็อก D)
select
  c.display_name                                                as "ชื่อที่แสดงของผู้ใช้",
  (select count(*) from billing_documents b where b.contractor = c.display_name) as "มีงานในตารางวางบิล"
from contractors c
where c.username = 'contractor11';


-- ---------------------------------------------------------------- บล็อก C
-- รายชื่อผู้รับเหมาที่ "ถูกใช้จริง" ในตารางวางบิล พร้อมจำนวนงาน
-- ใช้เทียบว่าทีมพี่สมชายถูกบันทึกไว้ด้วยชื่อว่าอะไรกันแน่
select coalesce(contractor, '(ไม่ระบุ)') as "ชื่อผู้รับเหมาในงาน", count(*) as "จำนวนแถว"
from billing_documents
group by contractor
order by count(*) desc;


