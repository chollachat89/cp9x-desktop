-- ถ้าตอนสร้างแถววางบิลใช้ชื่อสะกดต่างจากนี้แม้แต่เว้นวรรคเดียว ผู้รับเหมาจะล็อกอินได้แต่ไม่เห็นงานของตัวเองเลย
-- หลังรันไฟล์นี้ ให้เช็คด้วยบล็อก B ด้านล่างว่าชื่อสะกดตรงกับที่ใช้ในงานจริงหรือไม่
